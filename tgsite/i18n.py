def formatta_data(dt: datetime, lang: str) -> str:
    mese = MESI.get(lang, MESI["en"])[dt.month - 1]
    if lang == "zh":
        return f"{dt.year}年{dt.month}月{dt.day}日"
    if lang == "de":
        return f"{dt.day}. {mese} {dt.year}"
    if lang == "es":
        return f"{dt.day} de {mese} de {dt.year}"
    if lang == "en":
        return f"{dt.day} {mese} {dt.year}"
    return f"{dt.day} {mese} {dt.year}"


def formatta_mese(dt: datetime, lang: str) -> str:
    mese = MESI.get(lang, MESI["en"])[dt.month - 1]
    if lang == "zh":
        return f"{dt.year}年{dt.month}月"
    return f"{mese} {dt.year}"


def etichette(lang: str) -> dict:
    return LINGUE.get(lang, LINGUE["en"])


def prefisso(lang: str, lingua_base: str = "it") -> str:
    """L'italiano sta nella radice del sito, le altre lingue in sottocartella."""
    return "" if lang == lingua_base else f"/{lang}"
